"""Extends the existing pipeline (Data -> Incident -> Hypothesis) with:

    Hypothesis -> Evidence Retrieval -> Hypothesis Validation -> Grounded Finding

For each hypothesis already generated by HypothesisGenerationService, this
retrieves incident-specific structured evidence (suppliers, contracts,
POs, shipments, inventory, customer orders -- via the existing ERP
tables) AND semantic evidence (contract clauses, historical incidents --
via the existing RAG vector store, filtered to the incident's supplier),
asks Gemini to validate the hypothesis against ONLY that retrieved
evidence, and persists everything to the existing Phase 3 schema
(EvidenceSource/Evidence/HypothesisEvidence/EvidenceAssessment/Verdict --
already in the database, never previously populated by any service).

No new tables. No new migration. This is the orchestrator those tables
were designed for.
"""
from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field
from typing import Literal

import groq
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

from logisense import models as m
from logisense.config import Settings
from logisense.repositories import (
    DocumentRepository,
    ERPQueryRepository,
    HypothesisRepository,
    IncidentRepository,
    InvestigationRunRepository,
    VerdictRepository,
)
from logisense.services.external.gdelt_connector import GDELTConnector
from logisense.services.external.maritime_connector import AISStreamConnector
from logisense.services.external.weather_connector import OpenMeteoConnector
from logisense.services.gemini_client import GroqClient, build_gemini_client
from logisense.services.rag.bm25_index import BM25Index
from logisense.services.rag.embeddings import EmbeddingClient, embed_query_text
from logisense.services.rag.hybrid_retriever import BM25Retriever, DenseRetriever, HybridRetriever
from logisense.services.rag.vector_store import ChromaVectorStore

logger = logging.getLogger(__name__)

_WEATHER_KEYWORDS = re.compile(r"\b(weather|storm|rain|snow|flood|wind|hurricane|typhoon|delay|disrupt|transport|route|climate)\b", re.IGNORECASE)
_MARITIME_KEYWORDS = re.compile(r"\b(ship|vessel|port|ocean|maritime|sea|cargo)\b", re.IGNORECASE)

ValidationStatus = Literal["supported", "partially_supported", "unsupported", "insufficient_evidence"]

_VALIDATION_INSTRUCTIONS = """You are validating a supply-chain incident hypothesis using ONLY the evidence listed below.

Evidence is numbered. Each item is a DATABASE RECORD (exact, authoritative fact from the operational database), a DOCUMENT PASSAGE (retrieved excerpt from a contract, policy, or historical record), or EXTERNAL EVIDENCE (real-world data from a weather, maritime, or news API). Treat external evidence as corroborating context, not authoritative fact -- do not treat an external event as the cause of an operational problem unless it is both temporally and geographically relevant to this specific supplier/shipment.

Rules:
1. Judge the hypothesis using ONLY the numbered evidence below. Do not use outside knowledge or invent facts, dates, quantities, or contract terms not present in the evidence.
2. For EVERY numbered evidence item, state whether it supports the hypothesis, contradicts it, or is neutral -- and how strongly (low/medium/high).
3. Determine an overall status: "supported" (multiple strong, consistent items support it, none meaningfully contradict), "partially_supported" (some support, but with gaps or minor contradictions), "unsupported" (evidence contradicts or is inconsistent with the hypothesis), or "insufficient_evidence" (the evidence is too thin or irrelevant to judge either way).
4. A confidence score from 0-100, reflecting how strongly the evidence (not the hypothesis's own wording) supports your status.
5. Actively look for evidence that would CONTRADICT the hypothesis, not just evidence that supports it -- a hypothesis is not "supported" just because no one looked for problems.
"""

_FINAL_VERDICT_INSTRUCTIONS = """You are producing the final grounded investigation finding for a supply-chain incident, after each individual hypothesis has already been validated against retrieved evidence.

Rules:
1. Base the finding ONLY on the hypothesis validations and evidence summaries below. Do not invent facts not present in them.
2. Identify the most likely root cause -- normally the hypothesis with "supported" status and the highest confidence. If none reached "supported", say so explicitly and note the investigation remains inconclusive rather than picking a favorite.
3. Describe business impact and any contract/SLA implications ONLY if the evidence actually supports them (e.g. a real contract penalty clause, a real customer order at risk) -- do not speculate.
4. Recommend a next action grounded in what a real procurement/logistics team could actually do given the evidence (e.g. "escalate per the contract's penalty clause", "request an updated ETA from the carrier") -- not a generic platitude.
5. Explicitly state remaining uncertainty and evidence gaps -- what would need to be checked next that this evidence doesn't cover.
"""


class EvidenceItemAssessment(BaseModel):
    evidence_number: int
    supports: bool
    contradicts: bool
    strength: Literal["low", "medium", "high"]
    reasoning: str = Field(max_length=500)


class HypothesisValidationResponse(BaseModel):
    status: ValidationStatus
    confidence: int = Field(ge=0, le=100)
    reasoning: str = Field(max_length=1500)
    contradicting_evidence_summary: str = Field(max_length=800)
    evidence_assessments: list[EvidenceItemAssessment]


class FinalVerdictResponse(BaseModel):
    root_cause_hypothesis_number: int | None
    confidence: int = Field(ge=0, le=100)
    explanation: str = Field(max_length=2000)
    supporting_evidence_summary: str = Field(max_length=1000)
    contradicting_evidence_summary: str = Field(max_length=1000)
    remaining_uncertainty: str = Field(max_length=800)
    evidence_gaps: str = Field(max_length=800)
    recommended_next_action: str = Field(max_length=800)


@dataclass(frozen=True)
class EvidenceItem:
    kind: Literal["database", "document", "external"]
    text: str
    reference: str
    relevance_score: float | None
    reliability_score: float | None
    metadata: dict


@dataclass(frozen=True)
class HypothesisValidationResult:
    hypothesis_id: int
    rank: int
    statement: str
    status: ValidationStatus
    confidence: int
    reasoning: str
    contradicting_evidence_summary: str
    evidence_items: list[EvidenceItem]
    citations: list[dict] = field(default_factory=list)


@dataclass(frozen=True)
class GroundedInvestigation:
    run_id: str
    hypothesis_results: list[HypothesisValidationResult]
    root_cause_hypothesis_id: int | None
    confidence: int
    explanation: str
    supporting_evidence_summary: str
    contradicting_evidence_summary: str
    remaining_uncertainty: str
    evidence_gaps: str
    recommended_next_action: str


class HypothesisEvidenceValidator:
    def __init__(
        self,
        session: Session,
        embedding_client: EmbeddingClient,
        vector_store: ChromaVectorStore,
        settings: Settings,
        gemini_client: GroqClient | None = None,
        rag_top_k: int = 5,
        rag_min_similarity: float = 0.2,
        bm25_index: BM25Index | None = None,
        rrf_k: int = 60,
        weather_connector: OpenMeteoConnector | None = None,
        gdelt_connector: GDELTConnector | None = None,
        maritime_connector: AISStreamConnector | None = None,
        enable_external_evidence: bool = False,
    ) -> None:
        self.session = session
        self.embedding_client = embedding_client
        self.vector_store = vector_store
        self.settings = settings
        self._client = gemini_client
        self.rag_top_k = rag_top_k
        self.rag_min_similarity = rag_min_similarity
        # External evidence (weather/maritime/news) is OFF by default --
        # it adds real network calls to every hypothesis validation, so
        # callers opt in explicitly (enable_external_evidence=True) or
        # by supplying a connector. When enabled, connectors default to
        # their standard construction (each gracefully reports itself
        # unavailable if its API key isn't configured -- this never
        # blocks validation, it just means less external evidence).
        self.enable_external_evidence = enable_external_evidence or any([weather_connector, gdelt_connector, maritime_connector])
        self.weather_connector = weather_connector or (OpenMeteoConnector() if self.enable_external_evidence else None)
        self.gdelt_connector = gdelt_connector or (GDELTConnector() if self.enable_external_evidence else None)
        self.maritime_connector = maritime_connector or (AISStreamConnector(settings) if self.enable_external_evidence else None)
        # Optional: when a BM25 index is supplied, evidence retrieval
        # uses real hybrid (dense + lexical) search via HybridRetriever,
        # so exact business identifiers (SUP-104, PO-83921) that dense
        # search alone might rank weakly are still found. Falls back to
        # dense-only retrieval (the prior behavior) when no BM25 index
        # is available -- e.g. rag-index-knowledge hasn't been re-run
        # since this feature was added.
        self.hybrid_retriever = (
            HybridRetriever(DenseRetriever(embedding_client, vector_store), BM25Retriever(bm25_index), rrf_k=rrf_k)
            if bm25_index is not None else None
        )

        self.runs = InvestigationRunRepository(session)
        self.incidents = IncidentRepository(session)
        self.hypotheses = HypothesisRepository(session)
        self.erp = ERPQueryRepository(session)
        self.documents = DocumentRepository(session)
        self.verdicts = VerdictRepository(session)

    def _gemini_client(self) -> GroqClient:
        if self._client is None:
            if not self.settings.groq_api_key:
                raise ValueError("GROQ_API_KEY must be set to validate hypotheses")
            self._client = build_gemini_client(self.settings)
        return self._client

    # -- main entry point -----------------------------------------------

    def validate_run(self, run_id: str) -> GroundedInvestigation:
        run = self.runs.get_by_run_id(run_id)
        if run is None:
            raise LookupError(f"Investigation run not found: {run_id}")
        hypotheses = self.hypotheses.get_by_run_id(run_id)
        if not hypotheses:
            raise LookupError(f"No hypotheses found for run {run_id} -- run generate-hypotheses first")

        incident = self.incidents.get_with_context(run.incident_id)
        supplier_id, source_supplier_id = self._resolve_incident_supplier(incident)

        source = m.EvidenceSource(
            run_id=run_id, category=m.EvidenceSourceCategory.INTERNAL,
            provider_name="Hybrid Structured+RAG Retrieval",
            status=m.ProviderStatus.AVAILABLE,
        )
        self.session.add(source)
        self.session.flush()

        results: list[HypothesisValidationResult] = []
        for hypothesis in hypotheses:
            evidence_items = self._gather_evidence(incident, hypothesis, supplier_id, source_supplier_id)
            result = self._validate_hypothesis(hypothesis, evidence_items, source)
            results.append(result)

        grounded = self._generate_final_verdict(run_id, results)
        self._persist_verdict(run_id, results, grounded)
        return grounded

    # -- structured evidence: incident-specific, not the whole DB --------

    @staticmethod
    def _resolve_incident_supplier(incident: m.Incident) -> tuple[int | None, str | None]:
        shipment = incident.shipment
        po = shipment.purchase_order if shipment else None
        if po and po.supplier:
            return po.supplier_id, po.supplier.source_supplier_id
        return None, None

    def _gather_evidence(
        self, incident: m.Incident, hypothesis: m.Hypothesis, supplier_id: int | None, source_supplier_id: str | None
    ) -> list[EvidenceItem]:
        items: list[EvidenceItem] = []
        shipment = incident.shipment
        po = shipment.purchase_order if shipment else None

        if supplier_id is not None:
            supplier = self.session.get(m.Supplier, supplier_id)
            items.append(EvidenceItem(
                kind="database", text=f"Supplier {supplier.name} ({source_supplier_id}).",
                reference=f"suppliers:{source_supplier_id}", relevance_score=0.9, reliability_score=0.95,
                metadata={"source_table": "suppliers", "source_id": source_supplier_id},
            ))

            perf = self.erp.get_live_supplier_performance(supplier_id)
            if perf:
                items.append(EvidenceItem(
                    kind="database",
                    text=(
                        f"Supplier {source_supplier_id} historical performance (computed from {perf['shipment_count']} "
                        f"real shipment records): on-time rate {perf['on_time_rate']}, average delay "
                        f"{perf['average_delay_days']} days, max delay {perf['max_delay_days']} days."
                    ),
                    reference=f"supplier_performance:{source_supplier_id}", relevance_score=0.9, reliability_score=0.95,
                    metadata={"source_table": "supplier_performance", "source_id": source_supplier_id},
                ))

            contract = self.erp.get_contract_for_supplier(supplier_id)
            if contract:
                items.append(EvidenceItem(
                    kind="database",
                    text=(
                        f"Contract {contract.source_contract_id}: agreed lead time {contract.agreed_lead_time} days, "
                        f"MOQ {contract.minimum_order_quantity}, SLA: {contract.sla}, penalty terms: {contract.penalty_terms}"
                    ),
                    reference=f"contracts:{contract.source_contract_id}", relevance_score=0.85, reliability_score=0.95,
                    metadata={"source_table": "contracts", "source_id": contract.source_contract_id},
                ))

        if po:
            items.append(EvidenceItem(
                kind="database",
                text=(
                    f"Purchase order {po.source_reference}: status={po.status.value}, order_date={po.order_date}, "
                    f"expected_ready_date={po.expected_ready_date}, total_value={po.total_value}."
                ),
                reference=f"purchase_orders:{po.source_reference}", relevance_score=0.9, reliability_score=0.95,
                metadata={"source_table": "purchase_orders", "source_id": po.source_reference},
            ))
            for item in self.erp.get_purchase_order_items(po.id):
                if item.product is None:
                    continue
                items.append(EvidenceItem(
                    kind="database",
                    text=(
                        f"PO item on {po.source_reference}: product {item.product.name} "
                        f"({item.product.source_product_id}), quantity={item.quantity}, unit_cost={item.unit_cost}."
                    ),
                    reference=f"purchase_order_items:{po.source_reference}/{item.product.source_product_id}",
                    relevance_score=0.7, reliability_score=0.95,
                    metadata={"source_table": "purchase_order_items", "source_id": item.product.source_product_id},
                ))
                for inv in self.erp.get_inventory_for_product_reference(item.product.source_product_id):
                    items.append(EvidenceItem(
                        kind="database",
                        text=(
                            f"Inventory for {item.product.source_product_id} at warehouse {inv.warehouse.code}: "
                            f"on_hand={inv.on_hand}, available={inv.available}, reorder_point={inv.reorder_point}, "
                            f"daily_demand={inv.daily_demand}."
                        ),
                        reference=f"inventory:{inv.warehouse.code}/{item.product.source_product_id}",
                        relevance_score=0.75, reliability_score=0.95,
                        metadata={"source_table": "inventory", "source_id": f"{inv.warehouse.code}/{item.product.source_product_id}"},
                    ))

        if shipment:
            items.append(EvidenceItem(
                kind="database",
                text=(
                    f"Shipment (id={shipment.id}): expected={shipment.expected_delivery_date}, "
                    f"actual={shipment.actual_delivery_date}, delay_days={shipment.delay_days}, "
                    f"carrier={shipment.carrier.name if shipment.carrier else 'unknown'}."
                ),
                reference=f"shipments:{shipment.id}", relevance_score=0.95, reliability_score=0.95,
                metadata={"source_table": "shipments", "source_id": str(shipment.id)},
            ))

        # RAG: semantic evidence (contract clauses, historical incidents),
        # filtered to this incident's supplier when known. Uses real
        # hybrid (dense + BM25) retrieval when a BM25 index is
        # available, so exact identifiers in the query (e.g. a supplier
        # ID mentioned in the hypothesis) are found even if dense search
        # alone ranks them weakly -- falls back to dense-only otherwise.
        query_text = f"{hypothesis.statement}\n{hypothesis.rationale}"
        where = {"supplier_id": source_supplier_id} if source_supplier_id else None

        if self.hybrid_retriever is not None:
            candidates = self.hybrid_retriever.retrieve(
                query_text, dense_top_k=self.rag_top_k, bm25_top_k=self.rag_top_k,
                final_top_k=self.rag_top_k, where=where,
            )
            for candidate in candidates:
                # A hybrid_score of 0 with no dense_score would mean the
                # chunk came from BM25 with no real term overlap --
                # min_similarity only applies when there IS a dense
                # score to compare against; BM25-only hits are kept
                # since BM25 rank order itself is the relevance signal.
                if candidate.dense_score is not None and candidate.dense_score < self.rag_min_similarity:
                    continue
                meta = candidate.metadata
                section = f", section: {meta.get('section')}" if meta.get("section") else ""
                items.append(EvidenceItem(
                    kind="document", text=candidate.text,
                    reference=f"{meta.get('category')}/{meta.get('filename')}{section}",
                    relevance_score=round(candidate.hybrid_score, 4), reliability_score=0.75,
                    metadata=dict(meta),
                ))
        else:
            query_embedding = embed_query_text(self.embedding_client, query_text)
            if query_embedding:
                matches = self.vector_store.query(query_embedding, top_k=self.rag_top_k, where=where)
                for match in matches:
                    if match.similarity < self.rag_min_similarity:
                        continue
                    meta = match.metadata
                    section = f", section: {meta.get('section')}" if meta.get("section") else ""
                    items.append(EvidenceItem(
                        kind="document", text=match.document_text,
                        reference=f"{meta.get('category')}/{meta.get('filename')}{section}",
                        relevance_score=round(match.similarity, 3), reliability_score=0.75,
                        metadata=dict(meta),
                    ))

        # External evidence (weather/maritime/news) -- OFF unless
        # explicitly enabled (adds real network calls). Only queried
        # when the hypothesis text is actually relevant to that source,
        # same keyword-gating discipline as MultiSourceInvestigationService,
        # and location/entity are derived from the supplier already
        # resolved above -- never guessed or asked of anyone.
        if self.enable_external_evidence and supplier_id is not None:
            supplier = self.session.get(m.Supplier, supplier_id)
            location_name = None
            if supplier.location:
                location_name = ", ".join(filter(None, [supplier.location.city, supplier.location.country]))
            hypothesis_text = f"{hypothesis.statement} {hypothesis.rationale}"

            if location_name and self.weather_connector and _WEATHER_KEYWORDS.search(hypothesis_text):
                result = self.weather_connector.get_weather_for_location(location_name)
                for ev in result.items:
                    items.append(EvidenceItem(
                        kind="external", text=ev.content, reference=ev.citation_text,
                        relevance_score=None, reliability_score=ev.confidence, metadata=ev.metadata,
                    ))

            if location_name and self.maritime_connector and _MARITIME_KEYWORDS.search(hypothesis_text):
                result = self.maritime_connector.get_vessel_activity_near(location_name)
                for ev in result.items:
                    items.append(EvidenceItem(
                        kind="external", text=ev.content, reference=ev.citation_text,
                        relevance_score=None, reliability_score=ev.confidence, metadata=ev.metadata,
                    ))

            if self.gdelt_connector:
                result = self.gdelt_connector.search_events(supplier.name)
                for ev in result.items:
                    items.append(EvidenceItem(
                        kind="external", text=ev.content, reference=ev.citation_text,
                        relevance_score=None, reliability_score=ev.confidence, metadata=ev.metadata,
                    ))

        return items

    # -- per-hypothesis validation -----------------------------------------------

    def _validate_hypothesis(
        self, hypothesis: m.Hypothesis, evidence_items: list[EvidenceItem], source: m.EvidenceSource
    ) -> HypothesisValidationResult:
        if not evidence_items:
            return HypothesisValidationResult(
                hypothesis_id=hypothesis.id, rank=hypothesis.rank, statement=hypothesis.statement,
                status="insufficient_evidence", confidence=0,
                reasoning="No structured records or document evidence could be retrieved for this hypothesis.",
                contradicting_evidence_summary="", evidence_items=[], citations=[],
            )

        # Persist raw Evidence rows regardless of the LLM's judgment --
        # what was retrieved is a fact independent of what Gemini concludes.
        evidence_db_rows: list[m.Evidence] = []
        for item in evidence_items:
            row = m.Evidence(
                source_id=source.id, evidence_text=item.text, evidence_reference=item.reference,
                relevance_score=item.relevance_score, reliability_score=item.reliability_score,
                evidence_metadata=item.metadata,
            )
            self.session.add(row)
            evidence_db_rows.append(row)
        self.session.flush()

        hyp_evidence_rows: list[m.HypothesisEvidence] = []
        for row in evidence_db_rows:
            link = m.HypothesisEvidence(
                hypothesis_id=hypothesis.id, evidence_id=row.id,
                evidence_question=f"Does this evidence support: {hypothesis.statement}",
            )
            self.session.add(link)
            hyp_evidence_rows.append(link)
        self.session.flush()

        prompt = self._build_validation_prompt(hypothesis, evidence_items)
        try:
            response = self._gemini_client().models.generate_content(
                model=self.settings.groq_model, contents=prompt,
                config={"response_mime_type": "application/json", "response_schema": HypothesisValidationResponse},
            )
        except groq.APIError as exc:
            logger.warning(
                "Hypothesis-validation call for hypothesis %s failed after all retry attempts (HTTP %s): %s",
                hypothesis.id, getattr(exc, "status_code", None), exc,
            )
            raise
        parsed = HypothesisValidationResponse.model_validate_json(response.text)

        citations = []
        strength_map = {"low": m.EvidenceStrength.LOW, "medium": m.EvidenceStrength.MEDIUM, "high": m.EvidenceStrength.HIGH}
        for assessment in parsed.evidence_assessments:
            idx = assessment.evidence_number - 1
            if not (0 <= idx < len(hyp_evidence_rows)):
                continue
            link = hyp_evidence_rows[idx]
            item = evidence_items[idx]
            self.session.add(m.EvidenceAssessment(
                hypothesis_evidence_id=link.id,
                supports_hypothesis=assessment.supports and not assessment.contradicts,
                contradicts_hypothesis=assessment.contradicts and not assessment.supports,
                strength=strength_map.get(assessment.strength, m.EvidenceStrength.LOW),
                reasoning=assessment.reasoning,
            ))
            citations.append({
                "evidence_number": assessment.evidence_number, "kind": item.kind, "reference": item.reference,
                "supports": assessment.supports, "contradicts": assessment.contradicts, "strength": assessment.strength,
                "text": item.text,
            })
        self.session.flush()

        return HypothesisValidationResult(
            hypothesis_id=hypothesis.id, rank=hypothesis.rank, statement=hypothesis.statement,
            status=parsed.status, confidence=parsed.confidence, reasoning=parsed.reasoning,
            contradicting_evidence_summary=parsed.contradicting_evidence_summary,
            evidence_items=evidence_items, citations=citations,
        )

    @staticmethod
    def _build_validation_prompt(hypothesis: m.Hypothesis, evidence_items: list[EvidenceItem]) -> str:
        blocks = []
        for i, item in enumerate(evidence_items, start=1):
            kind_label = {"database": "DATABASE RECORD", "document": "DOCUMENT PASSAGE", "external": "EXTERNAL EVIDENCE"}[item.kind]
            blocks.append(f"[{i}] {kind_label} ({item.reference})\n{item.text}")
        evidence_block = "\n\n".join(blocks)
        return (
            f"{_VALIDATION_INSTRUCTIONS}\n\n"
            f"HYPOTHESIS: {hypothesis.statement}\n"
            f"HYPOTHESIS RATIONALE (from initial generation, NOT evidence): {hypothesis.rationale}\n\n"
            f"EVIDENCE:\n{evidence_block}"
        )

    # -- final grounded verdict -----------------------------------------------

    def _generate_final_verdict(self, run_id: str, results: list[HypothesisValidationResult]) -> GroundedInvestigation:
        if all(r.status == "insufficient_evidence" for r in results):
            return GroundedInvestigation(
                run_id=run_id, hypothesis_results=results, root_cause_hypothesis_id=None, confidence=0,
                explanation="Insufficient evidence was retrieved to validate any hypothesis for this incident.",
                supporting_evidence_summary="", contradicting_evidence_summary="",
                remaining_uncertainty="No structured records or document evidence were available.",
                evidence_gaps="All evidence sources returned nothing relevant to this incident's supplier/PO/shipment.",
                recommended_next_action="Verify that ERP data and the knowledge base have been loaded/indexed for this incident's supplier.",
            )

        blocks = []
        for r in results:
            blocks.append(
                f"HYPOTHESIS #{r.rank}: {r.statement}\n"
                f"Status: {r.status}, Confidence: {r.confidence}\n"
                f"Reasoning: {r.reasoning}\n"
                f"Contradicting evidence: {r.contradicting_evidence_summary or 'none noted'}"
            )
        summary_block = "\n\n".join(blocks)
        prompt = f"{_FINAL_VERDICT_INSTRUCTIONS}\n\nHYPOTHESIS VALIDATIONS:\n{summary_block}"

        try:
            response = self._gemini_client().models.generate_content(
                model=self.settings.groq_model, contents=prompt,
                config={"response_mime_type": "application/json", "response_schema": FinalVerdictResponse},
            )
        except groq.APIError as exc:
            logger.warning(
                "Final-verdict call for run %s failed after all retry attempts (HTTP %s): %s",
                run_id, getattr(exc, "status_code", None), exc,
            )
            raise
        parsed = FinalVerdictResponse.model_validate_json(response.text)

        root_cause_id = None
        if parsed.root_cause_hypothesis_number is not None:
            for r in results:
                if r.rank == parsed.root_cause_hypothesis_number:
                    root_cause_id = r.hypothesis_id
                    break

        return GroundedInvestigation(
            run_id=run_id, hypothesis_results=results, root_cause_hypothesis_id=root_cause_id,
            confidence=parsed.confidence, explanation=parsed.explanation,
            supporting_evidence_summary=parsed.supporting_evidence_summary,
            contradicting_evidence_summary=parsed.contradicting_evidence_summary,
            remaining_uncertainty=parsed.remaining_uncertainty, evidence_gaps=parsed.evidence_gaps,
            recommended_next_action=parsed.recommended_next_action,
        )

    def _persist_verdict(self, run_id: str, results: list[HypothesisValidationResult], grounded: GroundedInvestigation) -> None:
        hypothesis_confidence_updates = [
            {
                "hypothesis_id": r.hypothesis_id, "rank": r.rank, "statement": r.statement,
                "validation_status": r.status, "confidence": r.confidence, "reasoning": r.reasoning,
                "contradicting_evidence_summary": r.contradicting_evidence_summary, "citations": r.citations,
            }
            for r in results
        ]
        external_items = [item for r in results for item in r.evidence_items if item.kind == "external"]
        external_evidence_summary = (
            "No external evidence sources were used in this validation."
            if not external_items else
            f"{len(external_items)} external evidence item(s) considered: " + "; ".join(sorted({item.reference for item in external_items}))
        )

        self.verdicts.upsert(
            run_id=run_id, root_cause_hypothesis_id=grounded.root_cause_hypothesis_id,
            confidence_score=float(grounded.confidence), explanation=grounded.explanation,
            supporting_evidence_summary=grounded.supporting_evidence_summary,
            contradicting_evidence_summary=grounded.contradicting_evidence_summary,
            internal_evidence_summary="Structured ERP records and indexed knowledge-base documents for this incident's supplier/PO/shipment.",
            external_evidence_summary=external_evidence_summary,
            remaining_uncertainty=grounded.remaining_uncertainty, evidence_gaps=grounded.evidence_gaps,
            recommended_next_action=grounded.recommended_next_action,
            hypothesis_confidence_updates=hypothesis_confidence_updates,
        )
        self.session.commit()
